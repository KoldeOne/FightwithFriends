export type Side = 'hero' | 'enemy';
export type HeroClass = 'warrior' | 'priest' | 'mage' | 'rogue';
export type EnemyKind = 'grunt' | 'archer' | 'runner' | 'shaman' | 'brute';
export type AttackStyle = 'melee' | 'ranged';
export type ResourceKind = 'rage' | 'mana' | 'energy';
export type AbilityId =
  | 'taunt'
  | 'heroicStrike'
  | 'thunderclap'
  | 'heal'
  | 'renew'
  | 'fortitude'
  | 'fireball'
  | 'polymorph'
  | 'counterspell'
  | 'sinisterStrike'
  | 'kick'
  | 'whirlwind'
  | 'shieldBlock'
  | 'powerShield'
  | 'prayerOfHealing'
  | 'iceLance'
  | 'blizzard'
  | 'eviscerate'
  | 'evasion';

/** Each class's always-on starting passive. */
export type PassiveId = 'autoTaunt' | 'fortitudeAura' | 'autoPolymorph' | 'stealth';

/** One of a hero's ability slots (max 5: the starting ability + 4 earned). */
export interface AbilitySlot {
  id: AbilityId;
  /** Seconds until it's ready again. */
  cooldown: number;
  /** Upgrade ranks from level-up rewards: +25% effect each / -20% cooldown each. */
  power?: number;
  haste?: number;
}

/** A ground area effect (e.g. Blizzard). */
export interface Zone {
  id: number;
  x: number;
  y: number;
  radius: number;
  remaining: number;
  tickTimer: number;
  damage: number;
  sourceId: number;
}
/** Passive traits: not part of the starting kit — saved as future reward options. */
export type TraitId = 'rage' | 'innerFocus' | 'arcaneSurge' | 'comboPoints';

/** A timed buff/debuff on a unit. */
export interface Effect {
  kind: 'hot' | 'dot' | 'slow' | 'fortitude' | 'sheep' | 'silence' | 'stealth' | 'block' | 'shield' | 'evasion';
  /** Seconds left. */
  remaining: number;
  /** For hot/dot: seconds between ticks, time to next tick, amount per tick. */
  tickEvery: number;
  tickTimer: number;
  amount: number;
  sourceId: number;
}

/** Target id used when an enemy is attacking the gate. */
export const GATE_ID = -1;

export interface Unit {
  id: number;
  side: Side;
  kind: HeroClass | EnemyKind;
  label: string;
  x: number;
  y: number;
  radius: number;
  hp: number;
  maxHp: number;
  /** Damage per auto attack. */
  damage: number;
  /** Seconds between auto attacks. */
  attackInterval: number;
  /** Seconds until the next attack is ready. */
  cooldown: number;
  /** Reach measured edge-to-edge (gap between the two circles). */
  range: number;
  attackStyle: AttackStyle;
  /** Movement speed in px/s (heroes hold position: 0). */
  speed: number;
  /** Healing per heal cast (healers only). */
  heal?: number;
  /** Ignores heroes and heads straight for the gate. */
  goesForGate?: boolean;
  targetId: number | null;
  alive: boolean;
  /** Hero: multiplier on threat generated by damage (tanks are high). */
  threatMultiplier?: number;
  /** Hero: true for the party's tank (ignores threat caution, taunts). */
  isTank?: boolean;
  /** Enemy: threat per hero id. */
  threat?: Record<number, number>;
  /** Enemy: hero id forced as target by a taunt, and seconds remaining. */
  tauntedBy?: number;
  tauntTime?: number;
  /** Hero: class resource (rage / mana / energy). */
  resourceKind?: ResourceKind;
  resource?: number;
  maxResource?: number;
  /** Hero: ability slots. Slot 0 is the class's starting ability. */
  abilities?: AbilitySlot[];
  /** Active buffs/debuffs. */
  effects?: Effect[];
  /** Hero: the class's always-on starting passive, and its internal cooldown. */
  passive?: PassiveId;
  passiveCooldown?: number;
  /** Rogue: seconds without dealing/taking damage (to re-enter stealth). */
  outOfCombat?: number;
  /** Enemy: elite (tougher) and caster flags, used by auto-Polymorph priority. */
  isElite?: boolean;
  isCaster?: boolean;
  /** Current velocity (px/s) — movement eases in and out instead of snapping. */
  vx?: number;
  vy?: number;
  /** Hero: a small personal offset so the idle formation isn't rigid. */
  idleOffX?: number;
  idleOffY?: number;
  /** Hero: starting spot (AI teammates drift back here when it's quiet). */
  homeX?: number;
  homeY?: number;
  /** Hero: level (1 at the start of a run; +1 per wave cleared). */
  level?: number;
  /** Hero: general damage & healing multiplier from Might upgrades. */
  might?: number;
  /** Hero: passive traits earned so far (none at the start). */
  traits?: TraitId[];
  /** Rogue: combo points (0-5), only used with the Combo Points trait. */
  comboPoints?: number;
  /** Enemy: spell being cast, if any. */
  casting?: { spell: string; remaining: number; total: number; targetId: number };
  /** Enemy: seconds until it may start another cast. */
  castCooldown?: number;
  /** Enemy: bosses are immune to Polymorph. */
  isBoss?: boolean;
}

/** Aggro warning level shown on a hero. */
export type AggroLevel = 'none' | 'warning' | 'aggro';

export type BattleEvent =
  | { type: 'spawn'; id: number }
  | { type: 'attack'; from: number; to: number; style: AttackStyle; amount: number; ability?: AbilityId; big?: boolean }
  | { type: 'ability'; from: number; ability: AbilityId; to?: number }
  /** A projectile was fired; its damage lands `duration` seconds later (as an 'attack' event). */
  | { type: 'shoot'; from: number; to: number; duration: number; ability?: AbilityId }
  | { type: 'tick'; to: number; amount: number; kind: 'hot' | 'dot' }
  | { type: 'heal'; from: number; to: number; amount: number }
  | { type: 'taunt'; from: number; to: number }
  | { type: 'castStart'; from: number; spell: string; to: number; duration: number }
  | { type: 'castEnd'; from: number; interrupted: boolean }
  | { type: 'notice'; id: number; text: string; tone: 'good' | 'bad' | 'info' }
  | { type: 'death'; id: number };

export type Outcome = 'running' | 'victory' | 'defeat';

export interface SpawnDef {
  /** Seconds after the wave starts. */
  time: number;
  kind: EnemyKind;
  /** Horizontal spawn position. */
  x: number;
  /** Vertical spawn position (default: just above the top edge). Used for flanks. */
  y?: number;
}

export interface WaveDef {
  number: number;
  /** Shown in the wave intro, e.g. "Flanked!". */
  name?: string;
  spawns: SpawnDef[];
  /** Enemy health and damage multiplier (1 = base). */
  strength?: number;
}

/** What carries over between waves for one hero. */
export interface HeroBuild {
  level: number;
  abilities: { id: AbilityId; power: number; haste: number }[];
  traits: TraitId[];
  /** General upgrade ranks: +10% max health each / +10% damage & healing each. */
  vitality?: number;
  might?: number;
}
